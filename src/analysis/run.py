"""Run analyses A-G: (re)create the views, compute results, write CSVs and a results summary.

Usage (PowerShell, project root, venv active, database loaded and normalised):
    python -m src.analysis.run

Outputs:  data/processed/analysis/<A..G>_*.csv   result tables (documented in docs/methodology.md)
          docs/analysis_results.md               generated headline tables (do not edit)
"""

from __future__ import annotations

import sys
from datetime import date

import pandas as pd
from sqlalchemy import Engine, text

from src.analysis import analyses as an
from src.analysis import config as cfg
from src.analysis.scorecard import build_scorecard
from src.analysis.views import apply_views
from src.config import PROJECT_ROOT, ConfigError, load_settings
from src.db import get_engine

OUT_DIR = PROJECT_ROOT / "data" / "processed" / "analysis"
RESULTS_MD = PROJECT_ROOT / "docs" / "analysis_results.md"
VIEWS = {
    "monthly": "SELECT * FROM v_monthly_overall ORDER BY month",
    "pendency": "SELECT * FROM v_pendency_list",
    "long_pending": "SELECT * FROM v_long_pending_list",
    "closing": "SELECT * FROM v_closing_time_list",
    "grai": "SELECT * FROM v_grai",
    "flows": "SELECT * FROM v_ministry_monthly_flows",
    "reorganisations": "SELECT * FROM v_reorganisations",
}
NON_NUMERIC = {
    "canonical_name",
    "grai_group",
    "grai_methodology",
    "list",
    "filename",
    "serial",
    "relation",
    "successor",
}


def load_frames(engine: Engine) -> dict[str, pd.DataFrame]:
    frames = {}
    with engine.connect() as conn:
        for name, sql in VIEWS.items():
            df = pd.read_sql(text(sql), conn)
            for col in df.columns:
                if col in NON_NUMERIC or df[col].dtype == bool:
                    continue
                if df[col].dtype == object and df[col].map(lambda v: isinstance(v, date)).any():
                    continue  # dates stay dates
                if df[col].dtype == object:
                    df[col] = pd.to_numeric(df[col])  # PostgreSQL numeric -> Decimal -> float
            frames[name] = df
    return frames


def run_all(frames: dict[str, pd.DataFrame]) -> dict[str, pd.DataFrame]:
    n_reports = 53
    a_month, a_year = an.analysis_a(frames["monthly"])
    b_pend, b_long, b_close = an.analysis_b(
        frames["pendency"], frames["long_pending"], frames["closing"], n_reports, frames["reorganisations"]
    )
    c_listed, c_panel = an.analysis_c(frames["pendency"], frames["flows"])
    d_pairs, d_eras = an.analysis_d(frames["grai"])
    e_tests = an.analysis_e(frames["monthly"], frames["pendency"], frames["flows"])
    f_moy = an.analysis_f(frames["monthly"])
    g_class, g_sens = an.analysis_g(frames["flows"])
    scorecard = build_scorecard(frames)
    return {
        "A_overall_monthly": a_month,
        "A_overall_by_year": a_year,
        "B_pendency_list_appearances": b_pend,
        "B_long_pending_appearances": b_long,
        "B_closing_time_appearances": b_close,
        "C_listed_pending_changes": c_listed,
        "C_panel_pending_summary": c_panel,
        "D_rank_stability_pairs": d_pairs,
        "D_rank_stability_eras": d_eras,
        "E_trend_tests": e_tests,
        "F_month_of_year": f_moy,
        "G_demand_backlog": g_class,
        "G_sensitivity": g_sens,
        **scorecard,
    }


def _md_table(df: pd.DataFrame, cols: list[str], n: int | None = None, fmt: dict | None = None) -> list[str]:
    fmt = fmt or {}
    d = df[cols].head(n) if n else df[cols]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in d.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if c in fmt and pd.notna(v):
                cells.append(format(v, fmt[c]))
            elif isinstance(v, float) and pd.notna(v) and v.is_integer():
                cells.append(f"{int(v)}")  # counts, years, ranks
            elif isinstance(v, float):
                cells.append("" if pd.isna(v) else f"{v:,.2f}")
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def write_results_md(res: dict[str, pd.DataFrame]) -> None:
    e = res["E_trend_tests"]
    lines = [
        "# Analysis results (generated)",
        "",
        "Generated by `python -m src.analysis.run`. Do not edit by hand. Definitions, tests and limitations: "
        "[methodology.md](methodology.md). Full tables: `data/processed/analysis/`.",
        "",
        "> **Provisional:** the project owner's visual verification of sampled values "
        "([manual_verification.csv](manual_verification.csv)) is pending.",
        "",
        "## A. Aggregate series by calendar year (complete months only)",
        "",
        *_md_table(
            res["A_overall_by_year"],
            [
                "year",
                "complete_months",
                "partial_months",
                "mean_monthly_receipts",
                "mean_monthly_disposals",
                "disposal_to_receipt_ratio",
                "pending_last_complete_month",
            ],
            fmt={
                "mean_monthly_receipts": ",.0f",
                "mean_monthly_disposals": ",.0f",
                "disposal_to_receipt_ratio": ".3f",
                "pending_last_complete_month": ",.0f",
            },
        ),
        "",
        "## E. Trend tests (Mann-Kendall, Hamed-Rao modified; BH q-values within each family)",
        "",
        "Family F1 (aggregate series, core window):",
        "",
        *_md_table(
            e[e["family"].str.startswith("F1")],
            ["subject", "n", "tau", "sen_slope", "relative_slope_pct", "p_modified", "q_value", "conclusion"],
            fmt={
                "tau": ".3f",
                "sen_slope": ",.1f",
                "relative_slope_pct": ".2f",
                "p_modified": ".4f",
                "q_value": ".4f",
            },
        ),
        "",
    ]
    for fam in sorted(f for f in e["family"].unique() if not f.startswith("F1")):
        fe = e[e["family"] == fam]
        counts = fe["conclusion"].value_counts().to_dict()
        lines += [
            f"Family {fam}: {len(fe)} ministries tested; "
            + ", ".join(f"{k}: {v}" for k, v in counts.items())
            + ".",
            "",
        ]
        sig = fe[fe["conclusion"] != "no significant trend"].sort_values(
            "relative_slope_pct", ascending=False
        )
        if len(sig):
            lines += _md_table(
                sig,
                ["subject", "n", "tau", "relative_slope_pct", "q_value", "conclusion"],
                fmt={"tau": ".3f", "relative_slope_pct": ".2f", "q_value": ".4f"},
            ) + [""]
    b = res["B_pendency_list_appearances"]
    lines += [
        "## B. Most frequent appearances in the >1000-pending list (of 53 reports)",
        "",
        *_md_table(
            b,
            [
                "canonical_name",
                "reports_listed",
                "longest_consecutive_run",
                "current_run_to_latest",
                "core_window_reports_listed",
                "median_pending_when_listed",
                "reorganisation_note",
            ],
            n=15,
            fmt={"median_pending_when_listed": ",.0f"},
        ),
        "",
        f"{len(b)} of 92 ministries appeared at least once.",
        "",
        "## D. Ranking stability between consecutive reports (comparable pairs only)",
        "",
        *_md_table(
            res["D_rank_stability_eras"],
            [
                "methodology",
                "group",
                "pairs",
                "first_report",
                "last_report",
                "median_rho",
                "min_rho",
                "mean_top5_retained",
            ],
            fmt={"median_rho": ".3f", "min_rho": ".3f", "mean_top5_retained": ".2f"},
        ),
        "",
        "## G. Demand vs backlog (T6 panel, Sep 2024 - Jan 2026; band "
        f"±{cfg.STABLE_BAND_PCT_PER_MONTH}% of mean level per month)",
        "",
    ]
    g = res["G_demand_backlog"]
    lines += [f"Status: {g['status'].value_counts().to_dict()}", ""]
    q = (
        g[g["status"] == "classified"]["quadrant"]
        .value_counts()
        .rename_axis("quadrant")
        .reset_index(name="ministries")
    )
    lines += _md_table(q, ["quadrant", "ministries"]) + ["", "Sensitivity to the stable band:", ""]
    sens = res["G_sensitivity"]
    lines += _md_table(
        sens, ["stable_band_pct_per_month", "classified_ministries", "same_quadrant_as_default"]
    )
    sc = res["S_scorecard"]
    lines += [
        "",
        "## Scorecard (project construct, not an official rating; see scorecard.md)",
        "",
        f"Scored: {int(sc['score'].notna().sum())} of {len(sc)} ministries. Ranks are within GRAI group. "
        "The 90% rank interval comes from 1,000 random weightings.",
        "",
    ]
    for grp in ("A", "B"):
        top = sc[(sc["grai_group"] == grp) & sc["score"].notna()].sort_values("rank_in_group")
        lines += [f"Group {grp}, highest five and lowest five:", ""]
        cols = [
            "canonical_name",
            "score",
            "rank_in_group",
            "rank_random_p05",
            "rank_random_p95",
            "components_used",
        ]
        lines += _md_table(pd.concat([top.head(5), top.tail(5)]), cols, fmt={"score": ".1f"}) + [""]
    lines += _md_table(
        res["S_sensitivity"],
        ["variant", "group", "ministries", "spearman_vs_default", "max_rank_shift", "top_quartile_changes"],
        fmt={"spearman_vs_default": ".3f"},
    )
    lines += ["", "## F. Month-of-year receipts (descriptive only)", ""]
    lines += _md_table(
        res["F_month_of_year"],
        ["month_of_year", "years_observed", "mean_receipts", "ratio_to_overall_mean"],
        fmt={"mean_receipts": ",.0f", "ratio_to_overall_mean": ".3f"},
    )
    RESULTS_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    try:
        settings = load_settings()
    except ConfigError as exc:
        print(f"[config] {exc}", file=sys.stderr)
        return 1
    engine = get_engine(settings.database_url)
    try:
        print("Views:", ", ".join(apply_views(engine)))
        frames = load_frames(engine)
    finally:
        engine.dispose()
    results = run_all(frames)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, df in results.items():
        df.to_csv(OUT_DIR / f"{name}.csv", index=False, lineterminator="\n")
        print(f"{name}: {len(df)} rows")
    write_results_md(results)
    print(f"Wrote {OUT_DIR.relative_to(PROJECT_ROOT)} and {RESULTS_MD.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
