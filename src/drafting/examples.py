"""Phase 10 verification: five representative drafts, compared with their inputs and screened for facts.

Usage (PowerShell, project root, venv active):
    python -m src.drafting.examples          # -> docs/draft_examples.md

Inputs are synthetic development complaints (data/complaints/dev.jsonl) or written here, with invented
clarifications. Routing runs offline. A sixth, deliberately corrupted draft checks that the screen catches
an invented date, amount and allegation.
"""

from __future__ import annotations

import sys

from src.config import PROJECT_ROOT
from src.drafting.drafter import DraftRequest, build_draft, screen
from src.routing.router import Router
from src.routing.settings import RouterSettings

OUT = PROJECT_ROOT / "docs" / "draft_examples.md"

EXAMPLES = [
    {
        "label": "English, details given in the complaint and in clarifications",
        "complaint": "My PF final settlement claim filed on 12 March 2026 is still under process. Claim ID "
        "PF-2026-0457. The regional office helpline does not answer.",
        "language": "en",
        "clarifications": {
            "previous_attempts": "Visited the regional PF office on 2 May 2026; no written reply.",
            "action_requested": "Settle my claim and credit the amount to my bank account.",
        },
    },
    {
        "label": "Hindi complaint, Hindi draft, no details given (placeholders expected)",
        "complaint": "कोटेदार हर महीने पांच किलो कम राशन देता है और विरोध करने पर कार्ड रद्द करने की धमकी देता है।",
        "language": "hi",
        "clarifications": {},
    },
    {
        "label": "Hinglish complaint, English draft, partial clarifications",
        "complaint": "gas booking ho gayi par delivery boy extra 50 rupay maang raha hai",
        "language": "en",
        "clarifications": {
            "location": "Indane distributor, Sector 4 market",
            "dates": "Booked on 3 October 2026",
        },
    },
    {
        "label": "Router abstains (State matter): the draft leaves the department to the user",
        "complaint": "The police station refused to file an FIR about a chain snatching and told me to write it "
        "as lost.",
        "language": "en",
        "clarifications": {},
    },
    {
        "label": "Hindi complaint with amounts, Hindi draft, Hindi clarifications",
        "complaint": "एटीएम से पैसे निकालते समय मशीन ने पैसे नहीं दिए लेकिन खाते से 10,000 रुपये कट गए। बैंक में शिकायत की, अब तक वापस नहीं आए।",
        "language": "hi",
        "clarifications": {
            "reference_numbers": "शिकायत संख्या CMP-88213",
            "action_requested": "10,000 रुपये मेरे खाते में वापस जमा किए जाएं।",
        },
    },
]


def main() -> int:
    router = Router(settings=RouterSettings(), selector=None)
    lines = [
        "# Draft examples (generated)",
        "",
        "Generated by `python -m src.drafting.examples`. Synthetic inputs; routing offline. For each example: the",
        "input, the routing result, the draft, and the factuality screen (tokens and claim words in the draft that",
        "are not in the input). See [drafting.md](drafting.md).",
        "",
    ]
    summary = []
    for i, ex in enumerate(EXAMPLES, start=1):
        route = router.route(ex["complaint"])
        req = DraftRequest(
            complaint=ex["complaint"],
            language=ex["language"],
            department_key=route.department_key,
            department_name=route.department,
            category=route.category if not route.abstain else None,
            clarifications=ex["clarifications"],
        )
        d = build_draft(req)
        stats = d.department_statistics
        summary.append(
            (
                i,
                ex["label"],
                route.department or f"abstain ({route.abstain_reason})",
                len(d.placeholders),
                d.factcheck.passed,
            )
        )
        lines += [
            f"## Example {i}: {ex['label']}",
            "",
            "**Input complaint:**",
            "",
            f"> {ex['complaint']}",
            "",
            f"**Clarifications given:** {ex['clarifications'] or 'none'}",
            "",
            f"**Routing:** {route.department or 'abstained: ' + route.abstain_reason} "
            f"(method {route.method}; confidence {route.confidence} from {route.confidence_source}, uncalibrated)",
            "",
            "**Draft:**",
            "",
            "```text",
            d.text,
            "```",
            "",
            f"**Placeholders left for the user:** {len(d.placeholders)}. "
            f"**Factuality screen:** {'passed' if d.factcheck.passed else d.factcheck.model_dump()} "
            f"({d.factcheck.checked_tokens} factual tokens checked).",
            "",
            "**Statistics shown beside the draft (not in it):** "
            + (
                f"{stats.department}: "
                + "; ".join(f"{m.label} = {m.value} ({m.period})" for m in stats.metrics[:2])
                if stats and stats.available
                else "none (no department chosen)"
            ),
            "",
        ]
    # a corrupted draft must be caught
    ex = EXAMPLES[0]
    req = DraftRequest(complaint=ex["complaint"], clarifications=ex["clarifications"])
    d = build_draft(req, with_statistics=False)
    corrupted = d.text.replace(
        "Settle my claim",
        "Settle my claim of Rs 45,000 by 30 June 2026, failing which I will "
        "take legal action against the corrupt officials, and",
    )
    fc = screen(corrupted, req)
    lines += [
        "## Check: a deliberately corrupted draft",
        "",
        "Example 1's draft with an invented amount, deadline, threat and allegation inserted into the action requested:",
        "",
        f"- Unsupported factual tokens found: {fc.unsupported_tokens}",
        f"- Unsupported claim words found: {fc.unsupported_claim_words}",
        "",
        "## Summary",
        "",
        "| # | Example | Routed to | Placeholders | Factuality screen |",
        "|---|---|---|---|---|",
        *[
            f"| {i} | {label} | {dept} | {n} | {'passed' if ok else 'FLAGGED'} |"
            for i, label, dept, n, ok in summary
        ],
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    for row in summary:
        print(row)
    print("corrupted draft flags:", fc.unsupported_tokens, fc.unsupported_claim_words)
    return 0


if __name__ == "__main__":
    sys.exit(main())
