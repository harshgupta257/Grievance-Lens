"""Validate the mandate knowledge base and resolve it against the official Allocation of Business Rules text.

Usage (PowerShell, project root, venv active; run `python -m src.knowledge.aob` first):
    python -m src.knowledge.build

Inputs:  data/reference/mandates/departments.json   project-maintained entries (scope, references, keywords)
         data/reference/mandates/aob_items.csv       official AoB items (generated by src.knowledge.aob)
         data/reference/mandates/url_checks.csv      how each official URL was verified
         data/reference/ministries.csv               Part A canonical ministries
Output:  data/processed/knowledge/mandates.jsonl     one resolved record per department
         docs/mandate_kb_summary.md                  generated coverage table

Every problem is listed and the build stops without writing (exit 1). Nothing here calls the network.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pandas as pd

from src.config import PROJECT_ROOT

REF_DIR = PROJECT_ROOT / "data" / "reference" / "mandates"
DEPARTMENTS = REF_DIR / "departments.json"
AOB_ITEMS = REF_DIR / "aob_items.csv"
URL_CHECKS = REF_DIR / "url_checks.csv"
MINISTRIES = PROJECT_ROOT / "data" / "reference" / "ministries.csv"
OUT = PROJECT_ROOT / "data" / "processed" / "knowledge" / "mandates.jsonl"
SUMMARY_MD = PROJECT_ROOT / "docs" / "mandate_kb_summary.md"

ACCEPTED_URL_RESULTS = {"ok", "confirmed_by_official_link", "confirmed_by_directory"}
LANGUAGES = ("en", "hi", "hinglish")
DEVANAGARI = re.compile(r"[ऀ-ॿ]")
KEY_LIKE = re.compile(r"^[a-z0-9_]+$")


def load_inputs(
    departments: Path = DEPARTMENTS,
    aob: Path = AOB_ITEMS,
    urls: Path = URL_CHECKS,
    ministries: Path = MINISTRIES,
) -> tuple[dict, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    kb = json.loads(departments.read_text(encoding="utf-8"))
    items = pd.read_csv(aob, dtype={"item": str}, keep_default_na=False)
    items["omitted"] = items["omitted"].astype(str) == "True"
    return kb, items, pd.read_csv(urls, keep_default_na=False), pd.read_csv(ministries, keep_default_na=False)


def _ref_items(ref: dict, items: pd.DataFrame) -> pd.DataFrame:
    sel = items[(items["section"] == ref["section"]) & ~items["omitted"]]
    if "part" in ref:
        sel = sel[sel["part"] == ref["part"]]
    if "items" in ref:
        sel = sel[sel["item"].isin(ref["items"])]
    return sel


def validate(kb: dict, items: pd.DataFrame, urls: pd.DataFrame, ministries: pd.DataFrame) -> list[str]:
    problems = []
    deps = kb["departments"]
    keys = [d["ministry_key"] for d in deps]
    known_keys = set(ministries["ministry_key"])
    url_ok = dict(zip(urls["url"], urls["result"], strict=True))
    for dup in {k for k in keys if keys.count(k) > 1}:
        problems.append(f"{dup}: listed more than once")
    for d in deps:
        k = d["ministry_key"]
        if k not in known_keys:
            problems.append(f"{k}: not a ministry_key in data/reference/ministries.csv")
        allowed: set[tuple[str, str]] = set()
        for ref in d["aob_refs"]:
            if ref["section"] not in set(items["section"]):
                problems.append(f"{k}: AoB section not found: {ref['section']}")
                continue
            sel = _ref_items(ref, items)
            if sel.empty:
                problems.append(f"{k}: AoB reference resolves to no items: {ref}")
            for wanted in ref.get("items", []):
                if wanted not in set(sel["item"]):
                    problems.append(f"{k}: AoB item {ref['section']}:{wanted} missing or omitted")
            allowed |= set(zip(sel["section"], sel["item"], strict=True))
        for resp in d["grievance_responsibilities"]:
            if not resp["aob_items"]:
                problems.append(f"{k}: responsibility without AoB citation: {resp['text'][:50]}")
            for cite in resp["aob_items"]:
                section, _, item = cite.rpartition(":")
                if (section, item) not in allowed:
                    problems.append(f"{k}: citation {cite} is not among the entity's own AoB items")
        for url in d["official_urls"]:
            if url_ok.get(url) not in ACCEPTED_URL_RESULTS:
                problems.append(f"{k}: URL without an accepted check in url_checks.csv: {url}")
        for lang in LANGUAGES:
            words = d["keywords"].get(lang, [])
            if not words:
                problems.append(f"{k}: no {lang} keywords")
        if not any(DEVANAGARI.search(w) for w in d["keywords"].get("hi", [])):
            problems.append(f"{k}: Hindi keywords contain no Devanagari text")
        for o in d.get("overlaps", []):
            if KEY_LIKE.match(o["with"]) and o["with"] not in keys:
                problems.append(f"{k}: overlap refers to unknown KB entry {o['with']}")
        if d["mapping_status"] not in {"direct", "inferred"}:
            problems.append(f"{k}: mapping_status must be direct or inferred")
    return problems


def resolve(kb: dict, items: pd.DataFrame, urls: pd.DataFrame, ministries: pd.DataFrame) -> list[dict]:
    canonical = dict(zip(ministries["ministry_key"], ministries["canonical_name"], strict=True))
    checks = urls.set_index("url")
    records = []
    for d in kb["departments"]:
        official = pd.concat([_ref_items(ref, items) for ref in d["aob_refs"]])
        records.append(
            {
                "ministry_key": d["ministry_key"],
                "canonical_name": canonical[d["ministry_key"]],
                **{k: d[k] for k in ("official_name", "parent_ministry", "kb_role", "mapping_status")},
                # official Hindi names in Roman script, from the AoB section headings (e.g. "DAK VIBHAG")
                "aob_hindi_names": sorted({h.title() for h in official["section_hindi_name"] if h}),
                "official_mandate": [
                    {
                        "section": r.section,
                        "part": r.part,
                        "item": r.item,
                        "pdf_page": int(r.pdf_page),
                        "text": r.text,
                        "source": "aob_rules",
                    }
                    for r in official.itertuples()
                ],
                "official_urls": [
                    {"url": u, **checks.loc[u, ["checked_on", "http_status", "result", "note"]].to_dict()}
                    for u in d["official_urls"]
                ],
                "grievance_responsibilities": d["grievance_responsibilities"],
                "common_grievance_categories": d["common_grievance_categories"],
                "keywords": d["keywords"],
                "overlaps": d.get("overlaps", []),
                "notes": d.get("notes", ""),
                "verified_on": kb["about"]["verified_on"],
                "project_authored_fields": [
                    "grievance_responsibilities",
                    "common_grievance_categories",
                    "keywords",
                    "overlaps",
                    "notes",
                ],
            }
        )
    return records


def write(records: list[dict]) -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="\n") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    lines = [
        "# Mandate knowledge base: coverage (generated)",
        "",
        "Generated by `python -m src.knowledge.build`. Do not edit by hand. Method and caveats:",
        "[mandate_knowledge_base.md](mandate_knowledge_base.md).",
        "",
        "| Department (CPGRAMS name) | Official name | Mapping | AoB items | URL checks | Overlaps |",
        "|---|---|---|---|---|---|",
    ]
    for r in records:
        url_status = ", ".join(u["result"] for u in r["official_urls"])
        lines.append(
            f"| {r['canonical_name']} | {r['official_name']} | {r['mapping_status']} "
            f"| {len(r['official_mandate'])} "
            f"| {url_status} | {len(r['overlaps'])} |"
        )
    lines += [
        "",
        f"{len(records)} departments; {sum(len(r['official_mandate']) for r in records)} official items.",
    ]
    SUMMARY_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    kb, items, urls, ministries = load_inputs()
    problems = validate(kb, items, urls, ministries)
    if problems:
        print(f"Knowledge base invalid: {len(problems)} problem(s); nothing written.", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1
    records = resolve(kb, items, urls, ministries)
    write(records)
    print(
        f"{len(records)} departments -> {OUT.relative_to(PROJECT_ROOT)}, "
        f"{SUMMARY_MD.relative_to(PROJECT_ROOT)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
