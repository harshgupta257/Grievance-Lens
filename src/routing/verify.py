"""Phase 9 verification: route the 80 held-out development complaints and list every error and abstention.

Usage (PowerShell, project root, venv active):
    python -m src.routing.verify          # -> docs/router_verification.md

These are development data. The router's thresholds were tuned on all development data (including these
80) and the baseline's on these 80, so the numbers here are NOT an unbiased estimate; Phase 11 evaluates
on the isolated evaluation set.
"""

from __future__ import annotations

import sys
from collections import Counter

from src.config import PROJECT_ROOT
from src.routing.baseline import Baseline, load_dev
from src.routing.router import Router, load_thresholds
from src.routing.settings import RouterSettings

OUT = PROJECT_ROOT / "docs" / "router_verification.md"
SPECIAL = {"state_government", "out_of_scope", "insufficient_information"}


def outcome(item: dict, key: str | None) -> str:
    if item["intended_department"] in SPECIAL:
        return "correct abstention" if key is None else "wrong: routed a non-routable complaint"
    if key is None:
        return "abstained"
    return "correct" if key in item["acceptable_departments"] else "wrong department"


def main() -> int:
    items = load_dev()
    dev = [it for it in items if it["split"] == "dev"]
    train = [it for it in items if it["split"] == "train"]
    router = Router(settings=RouterSettings(), selector=None)
    names = router.names
    bl_cfg = load_thresholds("baseline") if False else None  # baseline settings live under "baseline"
    import json

    from src.routing.router import THRESHOLDS_PATH

    bl = json.loads(THRESHOLDS_PATH.read_text(encoding="utf-8"))["baseline"]
    baseline = Baseline(c=bl["C"]).fit(
        [it["text"] for it in train], [it["intended_department"] for it in train]
    )
    baseline.threshold = bl["threshold"]
    del bl_cfg
    rows = []
    for it in dev:
        r = router.route(it["text"])
        b = baseline.route(it["text"], names)
        rows.append((it, r, b))
    lines = [
        "# Router verification on development data (generated)",
        "",
        "Generated by `python -m src.routing.verify`. These 80 complaints are the held-out **development** split",
        "(synthetic). Router thresholds were tuned on all development data and the baseline's on these rows, so",
        "this is a check for errors and behaviour, **not** an unbiased accuracy estimate (see",
        "[evaluation.md](evaluation.md) for the isolated evaluation set). Mode: offline (`retrieval_rules`, lexical);",
        "the LLM selector was not run (no API key configured).",
        "",
        "| Outcome | Router (retrieval + rules) | Baseline (TF-IDF + LR) |",
        "|---|---|---|",
    ]
    r_counts = Counter(outcome(it, r.department_key) for it, r, _ in rows)
    b_counts = Counter(outcome(it, b.department_key) for it, _, b in rows)
    for k in sorted(set(r_counts) | set(b_counts)):
        lines.append(f"| {k} | {r_counts.get(k, 0)} | {b_counts.get(k, 0)} |")
    lines += [
        "",
        f"Total: {len(rows)}. Injection attempts flagged by the router: "
        f"{sum(r.injection_detected for _, r, _ in rows)}.",
        "",
        "## Every router error and abstention",
        "",
        "| id | lang | scenario | intended | router | reason / note |",
        "|---|---|---|---|---|---|",
    ]
    for it, r, _ in rows:
        o = outcome(it, r.department_key)
        if o != "correct":
            routed = names.get(r.department_key, "—") if r.department_key else f"abstain ({r.abstain_reason})"
            note = r.clarifying_question if r.abstain else f"alternatives: {', '.join(r.alternatives[:2])}"
            lines.append(
                f"| {it['id'][:13]} | {it['language']} | {it['scenario']} | "
                f"{names.get(it['intended_department'], it['intended_department'])} | {routed} | "
                f"{o}; {(note or '')[:110]} |"
            )
    lines += ["", "## Twenty examples in full (first 20 rows)", ""]
    for it, r, _ in rows[:20]:
        routed = r.department or f"abstain ({r.abstain_reason})"
        lines.append(
            f'- **{it["language"]}** "{it["text"][:140]}" -> **{routed}** '
            f"[{outcome(it, r.department_key)}; urgency {r.urgency}; "
            f"evidence: {r.evidence[0].citation if r.evidence else 'none'}]"
        )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"router {dict(r_counts)}")
    print(f"baseline {dict(b_counts)}")
    print(f"Wrote {OUT.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
