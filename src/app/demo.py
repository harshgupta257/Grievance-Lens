"""End-to-end demonstration against a running server: route -> performance -> draft, for three complaints.

Usage (PowerShell; start the server first in another window):
    uvicorn src.app.main:app --host 127.0.0.1 --port 8000
    python -m src.app.demo --base http://127.0.0.1:8000        # -> docs/app_demo.md
"""

from __future__ import annotations

import argparse
import sys

import httpx

from src.config import PROJECT_ROOT

OUT = PROJECT_ROOT / "docs" / "app_demo.md"
EXAMPLES = [
    (
        "English",
        "en",
        "en",
        "My speed post parcel with original certificates was booked on 2 October 2026 and "
        "tracking has shown in transit for 19 days.",
        {"reference_numbers": "Consignment EK-552190IN", "action_requested": "Trace and deliver the parcel."},
    ),
    (
        "Hindi",
        "auto",
        "hi",
        "मनरेगा में काम करवाया गया लेकिन मज़दूरी तीन महीने से नहीं मिली।",
        {"location": "ग्राम पंचायत कार्यालय"},
    ),
    (
        "Hinglish, State matter",
        "auto",
        "en",
        "padosi ne meri zameen pe kabza kar liya, police case nahi likh rahi",
        {},
    ),
]


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--base", default="http://127.0.0.1:8000")
    args = p.parse_args(argv)
    lines = [
        "# Application demo: three end-to-end requests (generated)",
        "",
        f"Generated by `python -m src.app.demo --base {args.base}` against a locally running server "
        "(offline router; no LLM). Each example calls `POST /route`, then `GET /ministry/{key}/performance` "
        "for the suggested department, then `POST /draft`. Inputs are synthetic.",
        "",
    ]
    with httpx.Client(base_url=args.base, timeout=60) as c:
        health = c.get("/health").json()
        lines += [f"`GET /health` -> `{health}`", ""]
        for label, lang, draft_lang, text, clar in EXAMPLES:
            r = c.post("/route", json={"text": text, "language": lang})
            route = r.json()
            lines += [f"## {label}", "", f"> {text}", "", f"`POST /route` -> HTTP {r.status_code}", ""]
            if route["abstain"]:
                lines += [
                    f"- Abstained: **{route['abstain_reason']}**",
                    f"- Clarifying question: {route['clarifying_question']}",
                    f"- Alternatives shown: {', '.join(route['alternatives']) or 'none'}",
                    f"- Possible State matter: {route['possible_state_matter']}",
                ]
            else:
                lines += [
                    f"- Suggested: **{route['department']}** (confidence {route['confidence']}, "
                    f"{route['confidence_source']}, uncalibrated); alternatives: {', '.join(route['alternatives'])}",
                    f"- Reason: {route['reason']}",
                    f"- Top evidence: {route['evidence'][0]['text'][:120]} [{route['evidence'][0]['citation']}]",
                ]
            lines += [
                f"- Urgency {route['urgency']}; language detected {route['language_detected']}; "
                f"missing information: {route['missing_information']}",
                "",
            ]
            key = route["department_key"]
            if key:
                perf = c.get(f"/ministry/{key}/performance").json()
                lines += [
                    f"`GET /ministry/{key}/performance` -> latest month {perf['latest_reporting_month']}; "
                    + "; ".join(f"{m['label']}: {m['value']} ({m['period']})" for m in perf["metrics"][:3]),
                    f"Backlog trend: {perf['backlog_trend']}",
                    "",
                ]
            d = c.post(
                "/draft",
                json={
                    "complaint": text,
                    "language": draft_lang,
                    "department_key": key,
                    "category": route["category"] if key else None,
                    "clarifications": clar,
                },
            ).json()
            lines += [
                f"`POST /draft` ({draft_lang}) -> {len(d['placeholders'])} placeholders; factuality screen "
                f"unsupported tokens {d['factcheck']['unsupported_tokens']}, claim words "
                f"{d['factcheck']['unsupported_claim_words']}",
                "",
                "```text",
                d["text"],
                "```",
                "",
            ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
