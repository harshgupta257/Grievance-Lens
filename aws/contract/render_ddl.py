"""Render all DDL from the schema contract, so Athena, Glue and Redshift can never disagree on a column.

    python -m aws.contract.render_ddl            # rewrite the generated .sql files
    python -m aws.contract.render_ddl --check    # exit 1 if any generated file is out of date (tests use this)

Outputs (do not edit by hand):
    aws/catalog/curated_tables.sql   Athena DDL for the curated Parquet tables (manual alternative to the
                                     Glue job's catalog publish; same columns, types and partition projection)
    aws/athena/raw_csv_tables.sql    Athena DDL for the raw CSV batch (benchmark baseline; all STRING)
    aws/redshift/schema.sql          Redshift Serverless warehouse: gl.* tables, stg.* staging, audit tables
    aws/redshift/views.sql           the shared flow-window view, ported from aws/athena/00_views.sql
    aws/redshift/analytics.sql       the five analyses, ported from aws/athena/01-05_*.sql

Placeholders such as ${CURATED_PREFIX} are substituted by the scripts that run the DDL
(aws/benchmarks/benchmark_runner.py, aws/scripts/refresh_warehouse.py); Athena itself has no variables.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

AWS = Path(__file__).resolve().parents[1]
CONTRACT = AWS / "contract" / "contract.json"
HEADER = "-- GENERATED by `python -m aws.contract.render_ddl` from aws/contract/contract.json ({h}). Do not edit.\n"

ATHENA_TYPES = {"int": "int", "double": "double", "boolean": "boolean", "date": "date", "string": "string"}

# Redshift physical design. Every table here is small (largest: grai_ranks, 4,490 rows), so the honest
# expectation is that Redshift's AUTO would choose ALL for nearly everything; the explicit choices below
# document the reasoning for the shape of the queries, and SVV_TABLE_INFO.skew_rows is checked after load.
#   * dimensions and every table under ~200 rows: DISTSTYLE ALL (a full copy on each node makes every join
#     to them local and costs nothing at this size);
#   * the three report-grain facts: DISTKEY(ministry_id), so ministry-to-ministry joins between them
#     (and with the ALL dimensions) are co-located; SORTKEY(report_number) because the analyses filter on
#     report ranges (#26-#45 panel, #29-#45 flows, #46-#53 era).
REDSHIFT_DESIGN = {
    "ministry_monthly": ('DISTSTYLE KEY DISTKEY ("ministry_id")', 'SORTKEY ("report_number", "ministry_id")'),
    "list_appearances": ('DISTSTYLE KEY DISTKEY ("ministry_id")', 'SORTKEY ("report_number", "list_code")'),
    "grai_ranks": ('DISTSTYLE KEY DISTKEY ("ministry_id")', 'SORTKEY ("report_number", "ministry_id")'),
    "overall_trend": ("DISTSTYLE ALL", 'SORTKEY ("month")'),
    "dim_month": ("DISTSTYLE ALL", 'SORTKEY ("month")'),
    "dim_report": ("DISTSTYLE ALL", 'SORTKEY ("report_number")'),
}
DEFAULT_DESIGN = ("DISTSTYLE ALL", "")


def redshift_type(col: dict) -> str:
    t = col["type"]
    if t == "string":
        return f"VARCHAR({col['max_length']})"
    return {"int": "INTEGER", "double": "DOUBLE PRECISION", "boolean": "BOOLEAN", "date": "DATE"}[t]


def athena_curated(contract: dict) -> str:
    out = [
        HEADER.format(h=contract["contract_hash"]),
        "-- Run in Athena after replacing ${CURATED_PREFIX} with the published ingestion's curated prefix,",
        "-- e.g. s3://<bucket>/curated/ingestion_id=2026-10-27_20261027T101500Z/  (see control/published/latest.json).",
        "-- The Glue job normally maintains these tables itself (glue:UpdateTable); use this only to rebuild them.",
        "",
        "CREATE DATABASE IF NOT EXISTS grievance_lens;",
        "",
    ]
    for t in contract["tables"]:
        cols = ",\n".join(f"  `{c['name']}` {ATHENA_TYPES[c['type']]}" for c in t["columns"])
        part = t.get("partition")
        out.append(f"-- {t['name']}: {t['grain']}")
        out.append(f"CREATE EXTERNAL TABLE IF NOT EXISTS grievance_lens.{t['name']} (\n{cols}\n)")
        if part:
            out.append(f"PARTITIONED BY (`{part['column']}` int)")
        out.append("STORED AS PARQUET")
        out.append(f"LOCATION '${{CURATED_PREFIX}}{t['name']}/'")
        props = [
            "'parquet.compression' = 'SNAPPY'",
            f"'grievance_lens.contract_hash' = '{contract['contract_hash']}'",
        ]
        if part:
            c = part["column"]
            props += [
                "'projection.enabled' = 'true'",
                f"'projection.{c}.type' = 'integer'",
                f"'projection.{c}.range' = '2022,2035'",
                f"'storage.location.template' = '${{CURATED_PREFIX}}{t['name']}/{c}=${{{c}}}/'",
            ]
        out.append("TBLPROPERTIES (\n  " + ",\n  ".join(props) + "\n);\n")
    return "\n".join(out)


def athena_raw(contract: dict) -> str:
    out = [
        HEADER.format(h=contract["contract_hash"]),
        "-- Raw CSV tables for ONE ingestion batch: the CSV-vs-Parquet benchmark baseline.",
        "-- ${RAW_BATCH_PREFIX} = s3://<bucket>/raw/powerbi/run_date=YYYY-MM-DD/batch=<id>/",
        "-- OpenCSVSerde reads every column as STRING and an empty field as '' (not NULL); the benchmark",
        "-- queries therefore cast with TRY_CAST(NULLIF(col, '') AS <type>), exactly what the Parquet path avoids.",
        "",
        "CREATE DATABASE IF NOT EXISTS grievance_lens_raw;",
        "",
    ]
    for t in contract["tables"]:
        cols = ",\n".join(f"  `{c['name']}` string" for c in t["columns"])
        out += [
            f"DROP TABLE IF EXISTS grievance_lens_raw.{t['name']};",
            f"CREATE EXTERNAL TABLE grievance_lens_raw.{t['name']} (\n{cols}\n)",
            "ROW FORMAT SERDE 'org.apache.hadoop.hive.serde2.OpenCSVSerde'",
            "WITH SERDEPROPERTIES ('separatorChar' = ',', 'quoteChar' = '\"', 'escapeChar' = '\\\\')",
            "STORED AS TEXTFILE",
            f"LOCATION '${{RAW_BATCH_PREFIX}}{t['name']}/'",
            "TBLPROPERTIES ('skip.header.line.count' = '1');",
            "",
        ]
    return "\n".join(out)


def redshift_schema(contract: dict) -> str:
    out = [
        HEADER.format(h=contract["contract_hash"]),
        "-- Redshift Serverless warehouse for Grievance Lens. Run once (idempotent), e.g. in Query Editor v2 or",
        "-- via aws/scripts/refresh_warehouse.py --create-schema.",
        "-- PRIMARY KEY / FOREIGN KEY are informational in Redshift: not enforced, but used by the planner.",
        "-- Uniqueness and referential integrity are enforced upstream by the Glue job before publishing.",
        "",
        "CREATE SCHEMA IF NOT EXISTS gl;   -- published star schema (what analysts and Power BI query)",
        "CREATE SCHEMA IF NOT EXISTS stg;  -- staging copies, loaded and validated before an atomic swap",
        "",
    ]
    for schema in ("gl", "stg"):
        for t in contract["tables"]:
            dist, sort = (
                REDSHIFT_DESIGN.get(t["name"], DEFAULT_DESIGN) if schema == "gl" else ("DISTSTYLE ALL", "")
            )
            # Column names are always double-quoted: the exports use reserved words such as "group".
            lines = [
                f'  "{c["name"]}" {redshift_type(c)}{"" if c["nullable"] else " NOT NULL"}'
                for c in t["columns"]
            ]
            if schema == "gl":
                lines.append("  PRIMARY KEY (" + ", ".join(f'"{k}"' for k in t["primary_key"]) + ")")
                lines += [
                    f'  FOREIGN KEY ("{fk["column"]}") REFERENCES gl.{fk["ref_table"]} ("{fk["ref_column"]}")'
                    for fk in t["foreign_keys"]
                ]
            body = ",\n".join(lines)
            tail = " ".join(x for x in (dist, sort) if x)
            out.append(f"CREATE TABLE IF NOT EXISTS {schema}.{t['name']} (\n{body}\n) {tail};\n")
    out += [
        "-- One row per refresh attempt that reached a stage; written inside the refresh transactions.",
        "CREATE TABLE IF NOT EXISTS gl.load_audit (",
        "  ingestion_id VARCHAR(96) NOT NULL,",
        "  run_date DATE NOT NULL,",
        "  batch_id VARCHAR(64) NOT NULL,",
        "  contract_hash VARCHAR(32) NOT NULL,",
        "  stage VARCHAR(16) NOT NULL,          -- STAGED | PUBLISHED",
        "  tables_loaded INTEGER NOT NULL,",
        "  rows_loaded BIGINT NOT NULL,",
        "  recorded_at TIMESTAMP NOT NULL DEFAULT GETDATE()",
        ") DISTSTYLE ALL SORTKEY (recorded_at);",
        "",
        "-- Which validated ingestion currently sits in stg.* (the publish step refuses anything else).",
        "CREATE TABLE IF NOT EXISTS stg.batch_marker (",
        "  ingestion_id VARCHAR(96) NOT NULL,",
        "  staged_at TIMESTAMP NOT NULL DEFAULT GETDATE()",
        ") DISTSTYLE ALL;",
        "",
    ]
    return "\n".join(out)


# The Athena queries are written in the SQL subset that Trino and Redshift share (no named WINDOW clause,
# no IS DISTINCT FROM, no FILTER, explicit casts before division). Porting them needs only these rewrites:
REDSHIFT_REWRITES = (
    ("grievance_lens.", "gl."),  # Glue database -> warehouse schema
    ("AS DOUBLE)", "AS DOUBLE PRECISION)"),  # Trino DOUBLE -> Redshift DOUBLE PRECISION
)


def to_redshift(sql: str) -> str:
    for old, new in REDSHIFT_REWRITES:
        sql = sql.replace(old, new)
    return sql.replace("(Athena / Trino)", "(Redshift)")


def redshift_views(contract: dict) -> str:
    src = (AWS / "athena" / "00_views.sql").read_text(encoding="utf-8")
    return (
        HEADER.format(h=contract["contract_hash"])
        + "-- Ported from aws/athena/00_views.sql.\n"
        + to_redshift(src)
    )


def redshift_analytics(contract: dict) -> str:
    parts = [
        HEADER.format(h=contract["contract_hash"]),
        "-- The five analyses, ported from aws/athena/01-05_*.sql with REDSHIFT_REWRITES (render_ddl.py).",
        "-- Each block starts with '-- name: <query>' so scripts can run them one at a time.",
        "-- Prerequisite: aws/redshift/views.sql (gl.v_flow_panel).",
        "",
    ]
    for f in sorted((AWS / "athena").glob("0[1-5]_*.sql")):
        parts += [f"-- name: {f.stem}", to_redshift(f.read_text(encoding="utf-8")).rstrip() + ";", ""]
    return "\n".join(parts)


TARGETS = {
    AWS / "catalog" / "curated_tables.sql": athena_curated,
    AWS / "athena" / "raw_csv_tables.sql": athena_raw,
    AWS / "redshift" / "schema.sql": redshift_schema,
    AWS / "redshift" / "views.sql": redshift_views,
    AWS / "redshift" / "analytics.sql": redshift_analytics,
}


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    stale = []
    for path, fn in TARGETS.items():
        text = fn(contract)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(AWS.parent)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(AWS.parent)}")
    if stale:
        print("out of date (run python -m aws.contract.render_ddl): " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
